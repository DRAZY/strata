#!/bin/sh
# Regenerate assets/third-party-licenses.tsv: every crate Strata builds with
# (all platforms, build dependencies included), its version and its license,
# shown in Help ▸ Licenses and Attribution. Run after changing dependencies;
# `cargo test` fails while the list is out of date with Cargo.lock.
set -e
cd "$(dirname "$0")/.."
cargo metadata --format-version 1 --locked | python3 -c '
import json, sys
m = json.load(sys.stdin)
rows = sorted({(p["name"], p["version"], (p.get("license") or "see the crate").replace("/", " OR "))
               for p in m["packages"] if p["name"] != "strata"})
print("# crate\tversion\tlicense (generated by scripts/third-party-licenses.sh)")
for r in rows:
    print("\t".join(r))
' > assets/third-party-licenses.tsv
echo "wrote assets/third-party-licenses.tsv"
