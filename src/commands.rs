    /// Single-key shortcuts in effect (defaults plus the user's keybindings.json).
    #[cfg(test)]
    pub fn keys(self) -> Vec<(Modifiers, Key)> {
        crate::keybindings::current().strokes(crate::keybindings::Target::Cmd(self))
    }

